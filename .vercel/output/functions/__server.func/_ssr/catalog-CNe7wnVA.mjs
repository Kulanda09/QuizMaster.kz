function stagger(subject, offset) {
	return {
		...subject,
		questions: subject.questions.map((question, index) => {
			const shift = (index + offset) % 4;
			if (shift === 0) return question;
			const options = [
				0,
				1,
				2,
				3
			].map((slot) => question.options[(slot - shift + 4) % 4]);
			const correct = (question.correct + shift) % 4;
			return {
				...question,
				options,
				correct
			};
		})
	};
}
var SUBJECTS = RAW_SUBJECTS.map((subject, subjectIndex) => stagger(subject, subjectIndex));
function getSubject(id) {
	return SUBJECTS.find((s) => s.id === id);
}
